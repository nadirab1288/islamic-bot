async def send_quiz(bot_obj, chat_id, uid):
    seen = get_quiz_seen(uid)
    avail = [i for i in range(len(QUIZ_QUESTIONS)) if i not in seen]
    if not avail:
        kb = InlineKeyboardMarkup(inline_keyboard=[
            [InlineKeyboardButton(text="Заново", callback_data="reset_q")],
            [InlineKeyboardButton(text="Меню", callback_data="back")]
        ])
        await bot_obj.send_message(chat_id, "МашаАллах! Все 25 вопросов пройдены!\n\nХочешь повторить?", reply_markup=kb)
        return
    qi = random.choice(avail)
    q = QUIZ_QUESTIONS[qi]
    btns = [[InlineKeyboardButton(text=o, callback_data=f"q:{qi}:{i}")] for i, o in enumerate(q["o"])]
    btns.append([InlineKeyboardButton(text="Меню", callback_data="back")])
    await bot_obj.send_message(
        chat_id,
        f"Вопрос ({len(seen)+1}/25):\n{q['q']}\n\nВыбери ответ:",
        reply_markup=InlineKeyboardMarkup(inline_keyboard=btns)
    )

